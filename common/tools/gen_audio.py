def note(p,w,v,e): return "%02x%x%x%x"%(p,w,v,e)

def sfx_line(speed,notes):
    notes=list(notes)+[(0,0,0,0)]*(32-len(notes))
    return "00%02x0000"%speed+"".join(note(*n) for n in notes)

